package com.example.collab.domain;

/**
 * 작업의 진행 상태.
 *
 * 과제가 "상태 종류는 지원자가 정한다"고 해서 아래 세 가지로 정했다.
 * - TODO        : 만들어졌지만 아직 시작하지 않은 작업. 작업 생성 시의 시작값이다.
 * - IN_PROGRESS : 누군가 진행 중인 작업.
 * - DONE        : 끝난 작업.
 *
 * 더 늘리지 않은 이유: 목록 조회의 상태 필터가 의미를 가지려면 상태가 서로 뚜렷이 구분돼야 하는데,
 * 이 세 가지면 "안 함 / 하는 중 / 끝남"이라는 구분이 빠짐없이 덮인다.
 * 보류·검토중 같은 값은 협업 규칙이 정해져야 쓸모가 생기고, 그 규칙은 이 과제 범위에 없다.
 *
 * 별도 코드 테이블로 빼지 않고 enum으로 둔 것도 같은 이유다. 테이블로 만들면
 * 사용자가 상태를 직접 추가할 수 있지만, 과제는 상태 종류를 지원자가 고정해 정하라고 했다.
 * DB에는 이름 문자열로 저장된다(ProjectMember.role의 @Enumerated 설명 참고).
 */
public enum TaskStatus {
	TODO,
	IN_PROGRESS,
	DONE
}
